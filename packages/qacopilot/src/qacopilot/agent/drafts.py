"""Build reminder emails. Code supplies every fact; the LLM writes only the opening sentences."""

from datetime import date

from pydantic import BaseModel

from qacopilot.llm import BaseLLMProvider
from qacopilot.mail import EmailMessage
from qacopilot.repositories import CertificateStatus

FALLBACK_INTRO = (
    "The following calibration certificates are overdue or due soon and need to be renewed."
)
_INTRO_SYSTEM = (
    "You write the opening of an internal email from a food manufacturer's quality team. "
    "Write one or two plain sentences asking the reader to arrange the calibrations listed "
    "below. Do not list instruments, dates or numbers; they are added separately. No greeting, "
    "no sign-off, no markdown."
)


class ReminderDraft(BaseModel):
    message: EmailMessage
    certificate_count: int
    overdue: int
    due_soon: int


def fact_table(certs: list[CertificateStatus]) -> str:
    lines = ["Serial | Instrument | Due | Status"]
    for c in certs:
        when = f"{-c.days_left} days overdue" if c.status == "overdue" else f"in {c.days_left} days"
        flag = " (UNVERIFIED reading)" if c.unverified else ""
        lines.append(
            f"{c.instrument_serial} | {c.instrument_description or '-'} | {c.next_due.isoformat()}"
            f" | {when}{flag}"
        )
    return "\n".join(lines)


def unverified_note(certs: list[CertificateStatus]) -> str:
    """A fixed sentence when some rows come from readings no one has confirmed (empty if none)."""
    n = sum(1 for c in certs if c.unverified)
    if not n:
        return ""
    return (
        f"{n} of these {'is an unverified reading' if n == 1 else 'are unverified readings'} "
        "(a poor scan or odd dates, not yet confirmed by a person): check "
        f"{'it' if n == 1 else 'them'} against the original certificate before acting."
    )


async def write_intro(llm: BaseLLMProvider | None, window_days: int) -> str:
    """One or two sentences from the LLM, or the fixed fallback if it is unavailable or odd."""
    if llm is None:
        return FALLBACK_INTRO
    try:
        resp = await llm.chat(
            [
                {"role": "system", "content": _INTRO_SYSTEM},
                {"role": "user", "content": f"Certificates due within {window_days} days."},
            ],
            thinking=False,
            max_tokens=2048,
        )
    except Exception:
        return FALLBACK_INTRO
    text = " ".join(resp.content.split())
    # The model must not smuggle in facts, links or markup; anything odd falls back.
    if not 20 <= len(text) <= 400 or any(ch.isdigit() for ch in text) or "http" in text.lower():
        return FALLBACK_INTRO
    return text


async def build_reminder(
    certs: list[CertificateStatus],
    recipients: list[str],
    llm: BaseLLMProvider | None,
    window_days: int,
    today: date | None = None,
) -> ReminderDraft:
    today = today or date.today()
    overdue = sum(1 for c in certs if c.status == "overdue")
    intro = await write_intro(llm, window_days)
    parts = [intro, fact_table(certs)]
    if caution := unverified_note(certs):
        parts.append(caution)
    parts.append(
        f"Generated by KVACK on {today.isoformat()} from the calibration records. "
        "Please check the dates against the certificates before acting."
    )
    body = "\n\n".join(parts)
    subject = f"Calibration reminders: {len(certs)} due within {window_days} days"
    if overdue:
        subject += f" ({overdue} overdue)"
    return ReminderDraft(
        message=EmailMessage(to=recipients, subject=subject, body=body),
        certificate_count=len(certs),
        overdue=overdue,
        due_soon=len(certs) - overdue,
    )
